/** @type {Map<string, {sourceFile: ts.SourceFile, imports: Map<string, string>}>} */
const parsedFiles = new Map();

function parseFile(file) {
  if (parsedFiles.has(file)) return parsedFiles.get(file);
  const text = readFileSync(file, "utf8");
  const sourceFile = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  const imports = new Map();
  for (const statement of sourceFile.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const spec = statement.moduleSpecifier.text;
    if (!spec.startsWith(".")) continue;
    const resolved = resolveImport(file, spec);
    if (!resolved) continue;
    const clause = statement.importClause;
    if (!clause) continue;
    if (clause.name) imports.set(clause.name.text, resolved);
    const bindings = clause.namedBindings;
    if (bindings && ts.isNamedImports(bindings)) {
      for (const element of bindings.elements) {
        imports.set((element.propertyName ?? element.name).text, resolved);
      }
    }
  }
  const entry = { sourceFile, imports };
  parsedFiles.set(file, entry);
  return entry;
}

function resolveImport(fromFile, spec) {
  const base = resolve(dirname(fromFile), spec);
  for (const candidate of [base, `${base}.ts`, join(base, "index.ts")]) {
    if (existsSync(candidate) && candidate.endsWith(".ts")) return candidate;
  }
  return null;
}

function stringValue(node) {
  if (!node) return undefined;
  if (ts.isStringLiteralLike(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  return undefined;
}

function propertyName(node) {
  if (!node) return undefined;
  if (ts.isIdentifier(node) || ts.isStringLiteralLike(node)) return node.text;
  return undefined;
}

/** 遍历 AST，收集所有 registerNodeType 调用。 */
function collectRegistrations(sourceFile) {
  const out = [];
  const visit = (node) => {
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (ts.isPropertyAccessExpression(callee) && callee.name.text === "registerNodeType") {
        const args = node.arguments;
        if (args.length === 1 && ts.isObjectLiteralExpression(args[0])) {
          const fields = {};
          for (const prop of args[0].properties) {
            if (!ts.isPropertyAssignment(prop)) continue;
            const name = propertyName(prop.name);
            if (!name) continue;
            fields[name] = prop.initializer;
          }
          if (fields.class) {
            out.push({
              classNode: fields.class,
              type: stringValue(fields.type),
              title: stringValue(fields.title),
              desc: stringValue(fields.desc),
            });
          }
        } else if (args.length >= 2 && stringValue(args[0])) {
          out.push({ classNode: args[1], type: stringValue(args[0]), title: undefined, desc: undefined });
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return out;
}

/** 在声明文件里找到类或工厂函数声明。 */
function findDeclaration(sourceFile, name) {
  let found = null;
  const visit = (node) => {
    if (found) return;
    if (ts.isClassDeclaration(node) && node.name?.text === name) found = node;
    else if (ts.isFunctionDeclaration(node) && node.name?.text === name) found = node;
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return found;
}

const BUILTIN_TYPE_NAMES = { EVENT: "event", ACTION: "action", DEFAULT: "any" };

function slotType(node) {
  const literal = stringValue(node);
  if (literal !== undefined) return literal || "any";
  if (!node) return "any";
  const text = node.getText().replace(/^BuiltInSlotType\./, "");
  return BUILTIN_TYPE_NAMES[text] ?? text;
}

function addSlot(list, seen, name, type) {
  const key = `${name}\u0000${type}`;
  if (seen.has(key)) return;
  seen.add(key);
  list.push({ name, type });
}

/** 提取 static slotLayout = { inputs: [...], outputs: [...] } */
function readSlotLayout(declaration, inputs, outputs, seenIn, seenOut) {
  if (!ts.isClassDeclaration(declaration)) return;
  for (const member of declaration.members) {
    if (!ts.isPropertyDeclaration(member) || !member.modifiers?.some((m) => m.kind === ts.SyntaxKind.StaticKeyword)) continue;
    const name = propertyName(member.name);
    if (name !== "slotLayout" || !member.initializer || !ts.isObjectLiteralExpression(member.initializer)) continue;
    for (const prop of member.initializer.properties) {
      if (!ts.isPropertyAssignment(prop)) continue;
      const dir = propertyName(prop.name);
      if (dir !== "inputs" && dir !== "outputs") continue;
      if (!ts.isArrayLiteralExpression(prop.initializer)) continue;
      for (const element of prop.initializer.elements) {
        if (!ts.isObjectLiteralExpression(element)) continue;
        let slotName = "";
        let type = "any";
        for (const field of element.properties) {
          if (!ts.isPropertyAssignment(field)) continue;
          const key = propertyName(field.name);
          if (key === "name") slotName = stringValue(field.initializer) ?? "";
          else if (key === "type") type = slotType(field.initializer);
        }
        if (dir === "inputs") addSlot(inputs, seenIn, slotName, type);
        else addSlot(outputs, seenOut, slotName, type);
      }
    }
  }
}

/** 提取构造器（或工厂函数）中直接调用的 this.addInput / addOutput / addWidget / addProperty。 */
function readConstructorCalls(declaration, info) {
  const seen = { inputs: new Set(), outputs: new Set(), widgets: new Set(), properties: new Set() };
  const bodies = [];
  if (ts.isClassDeclaration(declaration)) {
    const ctor = declaration.members.find((member) => ts.isConstructorDeclaration(member));
    if (ctor?.body) bodies.push(ctor.body);
  } else if (ts.isFunctionDeclaration(declaration) && declaration.body) {
    bodies.push(declaration.body);
  }

  const visit = (node, inNestedFunction) => {
    if (ts.isFunctionLike(node) && !ts.isConstructorDeclaration(node) && !inNestedFunction) {
      return;
    }
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (ts.isPropertyAccessExpression(callee) && callee.expression.kind === ts.SyntaxKind.ThisKeyword) {
        const method = callee.name.text;
        const args = node.arguments;
        if (method === "addInput" || method === "addOutput") {
          const name = stringValue(args[0]) ?? "";
          const type = slotType(args[1]);
          if (method === "addInput") addSlot(info.inputs, seen.inputs, name, type);
          else addSlot(info.outputs, seen.outputs, name, type);
        } else if (method === "addWidget") {
          // addWidget(type, name, value, callback, options) 或 addWidget(name, value, ...)
          const first = stringValue(args[0]);
          const second = stringValue(args[1]);
          let name = first ?? "";
          let type = "widget";
          if (second !== undefined) {
            type = first ?? "widget";
            name = second;
          }
          const key = `${name}\u0000${type}`;
          if (!seen.widgets.has(key)) {
            seen.widgets.add(key);
            info.widgets.push({ name, type });
          }
        } else if (method === "addProperty") {
          const name = stringValue(args[0]);
          if (name && !seen.properties.has(name)) {
            seen.properties.add(name);
            info.properties.push(name);
          }
        }
      }
    }
    ts.forEachChild(node, (child) => visit(child, inNestedFunction || ts.isFunctionLike(node)));
  };

  for (const body of bodies) {
    for (const statement of body.statements) visit(statement, false);
  }

  // static propertyLayout = [{ name: "value", ... }]
  if (ts.isClassDeclaration(declaration)) {
    for (const member of declaration.members) {
      if (!ts.isPropertyDeclaration(member) || !member.modifiers?.some((m) => m.kind === ts.SyntaxKind.StaticKeyword)) continue;
      if (propertyName(member.name) !== "propertyLayout") continue;
      if (!member.initializer || !ts.isArrayLiteralExpression(member.initializer)) continue;
      for (const element of member.initializer.elements) {
        if (!ts.isObjectLiteralExpression(element)) continue;
        for (const field of element.properties) {
          if (!ts.isPropertyAssignment(field) || propertyName(field.name) !== "name") continue;
          const name = stringValue(field.initializer);
          if (name && !seen.properties.has(name)) {
            seen.properties.add(name);
            info.properties.push(name);
          }
        }
      }
    }
  }

  // properties 字段初始化的键也视为可编辑属性
  if (ts.isClassDeclaration(declaration)) {
    for (const member of declaration.members) {
      if (!ts.isPropertyDeclaration(member)) continue;
      if (propertyName(member.name) !== "properties") continue;
      if (!member.initializer || !ts.isObjectLiteralExpression(member.initializer)) continue;
      for (const prop of member.initializer.properties) {
        const name = propertyName(prop.name);
        if (name && !seen.properties.has(name)) {
          seen.properties.add(name);
          info.properties.push(name);
        }
      }
    }
  }
}

/** 读取类/函数上的标题、说明赋值：X.title = "..."、X.desc = "..." 或 static title。 */
function readTitles(sourceFile, name) {
  const result = {};
  const visit = (node) => {
    if (
      ts.isExpressionStatement(node) &&
      ts.isBinaryExpression(node.expression) &&
      node.expression.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
      ts.isPropertyAccessExpression(node.expression.left) &&
      ts.isIdentifier(node.expression.left.expression) &&
      node.expression.left.expression.text === name
    ) {
      const key = node.expression.left.name.text;
      const value = stringValue(node.expression.right);
      if ((key === "title" || key === "desc") && value !== undefined) result[key] = value;
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return result;
}

function readDeclaration(sourceFile, name, filePath) {
  const declaration = findDeclaration(sourceFile, name);
  if (!declaration) return null;
  const info = { title: undefined, desc: undefined, inputs: [], outputs: [], widgets: [], properties: [], sourceFile: filePath };
  readSlotLayout(declaration, info.inputs, info.outputs, new Set(), new Set());
  readConstructorCalls(declaration, info);
  const titles = readTitles(sourceFile, name);
  info.title = titles.title;
  info.desc = titles.desc;

  if (ts.isClassDeclaration(declaration)) {
    for (const member of declaration.members) {
      const isStatic = member.modifiers?.some((m) => m.kind === ts.SyntaxKind.StaticKeyword);
      if (!isStatic || !ts.isPropertyDeclaration(member)) continue;
      const key = propertyName(member.name);
      if (key !== "title" && key !== "desc") continue;
      const value = stringValue(member.initializer);
      if (value !== undefined && info[key] === undefined) info[key] = value;
    }
  }
  return info;
}

/** 从一个源文件里解析出该文件注册的所有节点。 */
function readNodesFromFile(file, pkg) {
  const { sourceFile, imports } = parseFile(file);
  const nodes = [];
  for (const reg of collectRegistrations(sourceFile)) {
    const className = reg.classNode.getText(sourceFile);
    const classFile = imports.get(className) ?? file;
    const classInfo = readDeclaration(parseFile(classFile).sourceFile, className, classFile);
    nodes.push({
      type: reg.type,
      title: reg.title ?? classInfo?.title ?? reg.type,
      desc: reg.desc ?? classInfo?.desc ?? "",
      inputs: classInfo?.inputs ?? [],
      outputs: classInfo?.outputs ?? [],
      widgets: classInfo?.widgets ?? [],
      properties: classInfo?.properties ?? [],
      sourceFile: classInfo?.sourceFile ?? classFile,
      package: pkg.name,
    });
  }
  return nodes;
}

function collectPacks() {
  const packagesDir = join(repoRoot, "packages");
  const packs = [];

  const coreFiles = readdirSync(join(packagesDir, "core", "src", "nodes"))
    .filter((name) => name.endsWith(".ts"))
    .map((name) => join(packagesDir, "core", "src", "nodes", name))
    .filter((file) => collectRegistrations(parseFile(file).sourceFile).length > 0);
  packs.push({ name: "core", files: coreFiles, dir: join(packagesDir, "core") });

  const nodePacks = readdirSync(packagesDir)
    .filter((name) => name.startsWith("nodes-"))
    .sort();
  for (const dirName of nodePacks) {
    const dir = join(packagesDir, dirName);
    const installFile = join(dir, "src", "install.ts");
    if (!existsSync(installFile)) continue;
    packs.push({ name: dirName.replace(/^nodes-/, ""), label: dirName, files: [installFile], dir });
  }
  return packs;
}

function mdEscape(text) {
  return String(text).replace(/\|/g, "\\|");
}

function renderSlots(slots, sep, none) {
  if (!slots.length) return none;
  return slots.map((slot) => `\`${slot.name || "—"}: ${slot.type}\``).join(sep);
}

function renderList(items, sep, none) {
  if (!items.length) return none;
  return items.map((item) => `\`${item}\``).join(sep);
}

function nodeAnchor(type) {
  return type.toLowerCase().replace(/[^a-z0-9\u4e00-\u9fa5]+/g, "-").replace(/^-+|-+$/g, "");
}

function renderNode(node, t) {
  const lines = [];
  const title = node.title || node.type;
  lines.push(`## \`${node.type}\` — ${mdEscape(title)} {#${nodeAnchor(node.type)}}`);
  lines.push("");
  lines.push(node.desc ? mdEscape(node.desc) : t.noDesc);
  lines.push("");
  lines.push(`- ${t.labels.inputs}${t.colon}${renderSlots(node.inputs, t.sep, t.none)}`);
  lines.push(`- ${t.labels.outputs}${t.colon}${renderSlots(node.outputs, t.sep, t.none)}`);
  if (node.widgets.length) lines.push(`- ${t.labels.widgets}${t.colon}${renderSlots(node.widgets, t.sep, t.none)}`);
  if (node.properties.length) lines.push(`- ${t.labels.properties}${t.colon}${renderList(node.properties, t.sep, t.none)}`);
  const rel = relative(repoRoot, node.sourceFile).split("\\").join("/");
  lines.push(`- ${t.labels.source}${t.colon}[${rel.split("/").pop()}](${REPO_URL}/${rel})`);
  lines.push("");
  return lines;
}

function typePrefixes(nodes) {
  const prefixes = new Set(nodes.map((node) => node.type.split("/")[0]));
  return [...prefixes].sort().map((prefix) => `\`${prefix}/*\``).join("、");
}

function generate(localeKey) {
  const t = LOCALES[localeKey];
  const packs = collectPacks();
  const expected = new Map();
  const summary = [];

  for (const pack of packs) {
    const nodes = [];
    for (const file of pack.files) nodes.push(...readNodesFromFile(file, pack));
    nodes.sort((a, b) => (a.type < b.type ? -1 : a.type > b.type ? 1 : 0));
    const label = pack.name === "core" ? t.coreLabel : pack.label;
    summary.push({ ...pack, nodes, label });

    const sourcePath =
      pack.name === "core" ? "packages/core/src/nodes/" : relative(repoRoot, pack.files[0]).split("\\").join("/");
    const lines = [];
    lines.push(t.note);
    lines.push("");
    lines.push(t.catalogTitle(label));
    lines.push("");
    lines.push(t.countLine(nodes.length, sourcePath));
    lines.push("");
    lines.push(t.intro);
    lines.push("");
    for (const node of nodes) lines.push(...renderNode(node, t));
    expected.set(`${pack.name}.md`, lines.join("\n").replace(/\n+$/, "\n"));
  }

  // core 必须在第一位，其余保持包名顺序
  summary.sort((a, b) => (a.name === "core" ? -1 : b.name === "core" ? 1 : 0));

  const total = summary.reduce((sum, pack) => sum + pack.nodes.length, 0);
  const packaged = summary.filter((pack) => pack.name !== "core");
  const packagedTotal = packaged.reduce((sum, pack) => sum + pack.nodes.length, 0);

  const indexLines = [];
  indexLines.push(t.note);
  indexLines.push("");
  indexLines.push(t.indexTitle);
  indexLines.push("");
  indexLines.push(t.indexSummary(packaged.length, packagedTotal, summary[0].nodes.length, total));
  indexLines.push("");
  indexLines.push(t.installNote);
  indexLines.push("");
  indexLines.push(`| ${t.tableHead.join(" | ")} |`);
  indexLines.push(`| ${t.tableHead.map(() => "---").join(" | ")} |`);
  for (const pack of summary) {
    indexLines.push(`| ${pack.label} | ${pack.nodes.length} | ${typePrefixes(pack.nodes)} | [${pack.label}](./${pack.name}.md) |`);
  }
  indexLines.push("");
  indexLines.push(t.allTypes);
  indexLines.push("");
  for (const pack of summary) {
    for (const node of pack.nodes) {
      indexLines.push(
        `- \`${node.type}\` — ${mdEscape(node.title || node.type)} ([${pack.label}](./${pack.name}.md#${nodeAnchor(node.type)}))`,
      );
    }
  }
  indexLines.push("");
  expected.set("index.md", indexLines.join("\n"));

  return expected;
}

function main() {
  let stale = false;

  for (const localeKey of Object.keys(LOCALES)) {
    const t = LOCALES[localeKey];
    const expected = generate(localeKey);
    if (!checkOnly) mkdirSync(t.outDir, { recursive: true });

    for (const [name, content] of expected) {
      const target = join(t.outDir, name);
      const current = existsSync(target) ? readFileSync(target, "utf8") : null;
      const rel = relative(repoRoot, target).split("\\").join("/");
      if (checkOnly) {
        if (current !== content) {
          stale = true;
          console.error(`✗ ${rel} 与源码不一致，请运行 pnpm docs:nodes`);
        }
      } else if (current !== content) {
        writeFileSync(target, content);
        console.log(`更新 ${rel}`);
      }
    }

    if (checkOnly && existsSync(t.outDir)) {
      const known = new Set(expected.keys());
      for (const name of readdirSync(t.outDir)) {
        if (name.endsWith(".md") && !known.has(name)) {
          stale = true;
          console.error(`✗ ${relative(repoRoot, join(t.outDir, name)).split("\\").join("/")} 已无对应节点包，请删除`);
        }
      }
    }
  }

  if (checkOnly) {
    if (stale) process.exit(1);
    console.log("节点目录已是最新（中英文）");
  } else {
    console.log("节点目录生成完成（中英文）");
  }
}

main();
